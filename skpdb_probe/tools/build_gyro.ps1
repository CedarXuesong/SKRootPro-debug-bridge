param([string]$Ndk=$env:ANDROID_NDK_ROOT)
$ErrorActionPreference='Stop'
$moduleRoot=Split-Path -Parent $PSScriptRoot
$out=Join-Path $moduleRoot 'obj/gyro-payload'
New-Item -ItemType Directory -Force $out | Out-Null
$bin=Join-Path $Ndk 'toolchains/llvm/prebuilt/windows-x86_64/bin'
& (Join-Path $bin 'aarch64-linux-android29-clang++.cmd') -Oz -static -nostdlib -ffreestanding -fno-builtin -fno-stack-protector -fno-exceptions -fno-rtti -fno-unwind-tables -fno-math-errno -mcmodel=tiny -mno-outline-atomics -mbranch-protection=standard '-Wl,--build-id=none' "-Wl,-T,$PSScriptRoot/gyro_payload.ld" (Join-Path $moduleRoot 'src/input/gyro_payload.cpp') -o "$out/payload.elf"
if($LASTEXITCODE -ne 0){throw 'gyro payload link failed'}
& (Join-Path $bin 'llvm-objcopy.exe') -O binary "$out/payload.elf" "$out/payload.bin"
if($LASTEXITCODE -ne 0){throw 'gyro payload extraction failed'}
$bytes=[IO.File]::ReadAllBytes("$out/payload.bin")
$text='// Generated by tools/build_gyro.ps1'+[Environment]::NewLine+'static const unsigned char kGyroPayload[] = {'+($bytes.ForEach({ '0x{0:x2}' -f $_ }) -join ',')+'};'+[Environment]::NewLine
[IO.File]::WriteAllText((Join-Path $moduleRoot 'src/input/gyro_payload_bytes.h'),$text,[Text.Encoding]::ASCII)
Write-Host "Gyro transform payload: $($bytes.Length) bytes"
