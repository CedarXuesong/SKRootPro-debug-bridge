$ErrorActionPreference = 'Stop'
$moduleRoot = Split-Path -Parent $PSScriptRoot
$source = Join-Path $moduleRoot 'src/wireless/webui'
$header = [Text.StringBuilder]::new()
[void]$header.AppendLine('// Generated by tools/build_webui.ps1; edit webui/ sources instead.')
foreach ($asset in @(@('index.html','kIndexHtml','SKPHTML'),@('app.css','kAppCss','SKPCSS'),@('app.js','kAppJs','SKPJS'))) {
    $content = [IO.File]::ReadAllText((Join-Path $source $asset[0]), [Text.Encoding]::UTF8)
    if ($content.Contains(")$($asset[2])`"")) { throw 'raw string delimiter in WebUI asset' }
    [void]$header.AppendLine("static const char $($asset[1])[] = R`"$($asset[2])($content)$($asset[2])`";")
}
[IO.File]::WriteAllText((Join-Path $moduleRoot 'src/wireless/webui_assets.h'), $header.ToString(), [Text.UTF8Encoding]::new($false))
Write-Host 'WebUI assets generated'
